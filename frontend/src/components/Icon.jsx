const SOLID_NAMES = new Set(Object.keys(SOLID));

function SolidIcon({ name, size, className, strokeWidth, title, style }) {
  const id = useId().replace(/[^a-zA-Z0-9]/g, "");
  return (
    <svg className={`ic ic-${name} ic-fill ${className}`} width={size} height={size} viewBox="0 0 24 24" role={title ? "img" : undefined} aria-hidden={title ? undefined : true} aria-label={title} style={style}>
      {title && <title>{title}</title>}
      <mask id={`ic${id}`} maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24">
        <g className="ic-solid" fill="none" stroke="#fff" strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round" color="#fff">
          {ICONS[name]}
        </g>
      </mask>
      <rect width="24" height="24" fill="currentColor" mask={`url(#ic${id})`} />
    </svg>
  );
}

export default function Icon({ name, size = 20, className = "", strokeWidth = 1.9, title, style }) {
  const glyph = ICONS[name];
  if (!glyph) return null;
  if (SOLID_NAMES.has(name)) return <SolidIcon name={name} size={size} className={className} strokeWidth={strokeWidth} title={title} style={style} />;
  // Line-only glyphs (arrows, ticks, crosses) are drawn a little heavier so they sit with the solid set.
  strokeWidth = Math.max(strokeWidth, 2.2);
  return (
    <svg
      className={`ic ic-${name} ${className}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      style={style}
    >
      {title && <title>{title}</title>}
      {glyph}
    </svg>
  );
}

